def render(prompts: dict[str, str] | None, role: str, **values: str) -> str:
    """Текст промпта роли с подставленными переменными (+ формат ответа). values: язык=…, надписи=…, лист=…"""
    text = ((prompts or {}).get(role) or _TEXTS[role])
    if role in ("analyze", "concept", "pick"):
        text += THUMB_RULES
    text += FORMAT.get(role, "")
    if role == "generate":
        text += "\n" + GENERATE_GUARD + "\n" + PROFANITY_EN + "\n" + THUMB_RULES_EN
    for key, value in values.items():
        text = text.replace("{" + key + "}", value)
    return text


def prune(prompts: list) -> list:
    """Свои промпты для хранения: без неизменённых копий стандартных (текущих и прежних версий) — иначе
    копия «замораживает» стандартный промпт и его улучшения до тебя не доходят."""
    current = {role: text for role, text in _TEXTS.items()}
    out = []
    for p in prompts or []:
        if not isinstance(p, dict) or p.get("role") not in ROLES:
            continue
        up = _upgrade(p)
        if str(p.get("id") or "").startswith("default-") and up.get("text") == current[p["role"]] \
                and p.get("name", "Стандартный") == "Стандартный":
            continue
        out.append(p)
    return out
