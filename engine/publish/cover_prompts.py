def _upgrade(p: dict) -> dict:
    import hashlib

    role = p.get("role")
    if hashlib.sha1(str(p.get("text") or "").encode()).hexdigest()[:12] in _OLD_DEFAULTS.get(role, ()):
        return {**p, "text": _TEXTS[role]}
    return p


def library(cfg: dict[str, Any]) -> list[dict[str, str]]:
    """Свои промпты (если заведены) — иначе стандартные. Роль без своих версий — стандартная."""
    own = [_upgrade(p) for p in cfg.get("cover_prompts") or [] if isinstance(p, dict) and p.get("role") in ROLES
           and str(p.get("text") or "").strip()]
    have = {p["role"] for p in own}
    return own + [d for d in DEFAULTS if d["role"] not in have]


def active(cfg: dict[str, Any]) -> dict[str, str]:
    """Роль → текст выбранного промпта (выбор — cover_prompt {роль: id}; нет такого — первый у роли)."""
    lib = library(cfg)
    chosen = cfg.get("cover_prompt") if isinstance(cfg.get("cover_prompt"), dict) else {}
    out: dict[str, str] = {}
    for role in ROLES:
        mine = [p for p in lib if p["role"] == role]
        pick = next((p for p in mine if p["id"] == chosen.get(role)), mine[0] if mine else None)
        out[role] = str(pick["text"]) if pick else _TEXTS[role]
    return out


