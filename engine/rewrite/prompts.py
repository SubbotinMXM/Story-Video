def prompts_of(cfg_prompts: object) -> list[dict]:
    """Промпты из настроек; пусто — промпты по умолчанию."""
    items = [p for p in (cfg_prompts or []) if isinstance(p, dict) and str(p.get("text") or "").strip()] if isinstance(cfg_prompts, list) else []
    return items or [dict(p) for p in DEFAULT_PROMPTS]


def pick_prompt(cfg_prompts: object, selected: object, section: str, prompt_id: str = "") -> dict:
    """Промпт для раздела: явно выбранный → выбранный в настройках раздела → первый промпт раздела."""
    items = prompts_of(cfg_prompts)
    sel = selected if isinstance(selected, dict) else {}
    for want in (prompt_id, str(sel.get(section) or "")):
        hit = next((p for p in items if p.get("id") == want), None)
        if hit:
            return hit
    hit = next((p for p in items if p.get("section") == section), None)
    if hit is None:
        raise ValueError(f"Нет промпта для раздела «{SECTIONS.get(section, section)}» — добавь его в Настройках")
    return hit


def language_names(code: str) -> tuple[str, str]:
    code = (code or "").split("-")[0].lower()
    return LANGUAGES.get(code, (code or "языке оригинала", code or "языке оригинала"))


def fill(prompt: str, *, language: str, words: str) -> str:
    """Подставить переменные. Старые промпты с «{указать язык}» тоже понимаем."""
    nom, prep = language_names(language)
    text = prompt.replace("{языке}", prep).replace("{язык}", nom).replace("{слов}", words or DEFAULT_WORDS)
    text = re.sub(r"\{указать язык\}", prep, text)
    text = re.sub(r"\{указать количество слов[^}]*\}", words or DEFAULT_WORDS, text)
    return text


def missing_variables(prompt: str) -> list[str]:
    """Каких переменных нет в промпте: без {язык}/{языке} язык из интерфейса не применится."""
    out = []
    if "{язык}" not in prompt and "{языке}" not in prompt and "{указать язык}" not in prompt:
        out.append("{язык}")
    if "{слов}" not in prompt and "{указать количество слов" not in prompt:
        out.append("{слов}")
    return out


def word_range(words: str) -> tuple[int, int]:
    """«7000–8000» → (7000, 8000); «5000» → (4500, 5500)."""
    nums = [int(n) for n in re.findall(r"\d+", (words or "").replace(" ", ""))]
    if len(nums) >= 2:
        lo, hi = sorted(nums[:2])
        return lo, hi
    if nums:
        return int(nums[0] * 0.9), int(nums[0] * 1.1)
    return 7000, 8000
